def celltext(v):
    if isinstance(v, dict):
        return str(v.get('text', '')).strip()
    return str(v).strip()

def col(row, idx):
    keys = sorted(row.keys())
    return celltext(row[keys[idx]]) if idx < len(keys) else ''

texts, tables = doc_text_and_tables(RP)
t32 = None
for t in tables:
    rows = [[celltext(v) for v in ([r[k] for k in sorted(r.keys())] if isinstance(r, dict) else r)]
            for r in t]
    if rows and rows[0] and rows[0][0].startswith('Наименование разделов'):
        t32 = rows
