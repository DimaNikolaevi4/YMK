mdk_row = t32[start]
assert mdk_row[2] == '140' and mdk_row[3] == '46', mdk_row

topics, cur = [], None
stage = 'theory'          # theory | practice
for r in t32[start + 1:end]:
    c0, c1, c2, c3, c4 = (r + ['', '', '', '', ''])[:5]
    if c0.startswith('Тема '):
        cur = {'name': c0, 'raw_total': int(c2 or 0), 'lessons': [], 'prep': 0}
        topics.append(cur)
        stage = 'theory'
        continue
    if not c0 and c1 in ('Содержание',):
        continue
    if c1 in ('Практическое занятие', 'Практические занятия', 'Практические работы',
              'Лабораторные занятия'):
        stage = 'practice'
        continue
    if cur is not None and c1 and not c0:
        try:
            hours = int(c3)
        except ValueError:
            hours = 0
        prep = int(c4) if c4.isdigit() else 0
        is_pr = (stage == 'practice')
        name = c2.strip()
        if is_pr:
            name = 'Практическое занятие № %s %s' % (c1, name)
        cur['lessons'].append({
            'rp_num': c1, 'name': name, 'hours': hours,
            'practice_prep': prep if is_pr else 0,
            'type': 'Практ. занятие' if is_pr else 'Урок',
        })
        if is_pr:
            cur['prep'] += hours  # часы ПЗ темы (для заголовка темы кол.3 = теория+ПЗ)

assert len(topics) == 8, [t['name'] for t in topics]
