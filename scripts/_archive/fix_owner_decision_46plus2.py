import json

DECISION = (' РЕШЕНИЕ ВЛАДЕЛЬЦА (09.09.2026, ответ на вопрос о расхождении УП↔РП): '
            '«46+2 — КТП 02.01 и 02.02 для слесарей делаем по РП» — приоритет новой версии РП '
            '(46 уч.занятий + 2 ч КДЗ = 48) над прежними УП 15.01.37 и ведомостью '
            '(48 уч.зан + 2 КДЗ = 50; старая теория 36/22 вместо РП 34/20). '
            'КТП не изменялись — уже соответствуют РП (коммит 2ef7a64); УП/ведомость формально '
            'устарели на 2 ч теории по каждому МДК, их правка — вне рамок КТП.')

for p in ['/home/z/my-project/YMK/scripts/data_02_01_s21.json',
          '/home/z/my-project/YMK/scripts/data_02_02_s21.json']:
    with open(p, encoding='utf-8') as f:
        d = json.load(f)
    c = d['rp_sync'].get('_comment', '')
    if 'РЕШЕНИЕ ВЛАДЕЛЬЦА (09.09.2026' in c:
        print(f'{p}: решение уже зафиксировано — пропуск')
        continue
    d['rp_sync']['_comment'] = c.rstrip() + DECISION
    with open(p, 'w', encoding='utf-8') as f:
        json.dump(d, f, ensure_ascii=False, indent=2)
    print(f'{p}: _comment дополнен решением владельца (+{len(DECISION)} симв.)')
