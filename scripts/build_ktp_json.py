def lessons_of(part, topic_num):
    return [x for x in part['items'] if x['kind'] == 'lesson' and x.get('_topic') == topic_num]


def works_of(part, topic_num):
    return [x for x in part['items'] if x['kind'] == 'work' and x.get('_topic') == topic_num]


def split_parts(part):
    """Проставить _topic каждому lesson/work по предшествующей теме."""
    cur = None
    for x in part['items']:
        if x['kind'] == 'topic':
            cur = x['num']
        x['_topic'] = cur
    return part


def topic_items(part, num):
    return [x for x in part['items'] if x.get('_topic') == num and x['kind'] in ('topic', 'lesson', 'work', 'block', 'att')]


def build_topics(part, mdk_name, ok, pk, cut=None, theory_equipment='ОИ1'):
    """Собирает topics[] для генератора. cut = {номер_темы: [номера уроков на срез]}."""
    cut = cut or {}
    split_parts(part)
    topics = []
    seen_topics = []
    n_lesson = 0
    for x in part['items']:
        if x['kind'] != 'topic':
            continue
        tnum = x['num']
        if tnum in seen_topics:
            continue
        seen_topics.append(tnum)
        cut_list = set(cut.get(tnum, []))
        les, works = [], []
        for y in part['items']:
            if y.get('_topic') != tnum:
                continue
            if y['kind'] == 'lesson':
                if y['num'] in cut_list:
                    continue
                n_lesson += 1
                les.append({
                    'num': n_lesson, 'name': y['name'], 'hours': y['hours'],
                    'practice_prep': 0, 'type': 'Урок', 'ok': ok, 'pk': pk,
                    'equipment': theory_equipment, 'task': 'Конспект лекций',
                    'control': 'Вх.контр' if n_lesson == 1 else 'Текущий контроль',
                })
            elif y['kind'] == 'work':
                n_lesson += 1
                prefix = 'Лабораторная работа № %s ' % y['num'] if y['type'] == 'lab' \
                    else 'Практическое занятие № %s ' % y['num']
                les.append({
                    'num': n_lesson, 'name': prefix + y['name'], 'hours': y['hours'],
                    'practice_prep': y['hours'],
                    'type': 'Лаб. работа' if y['type'] == 'lab' else 'Практ. занятие',
                    'ok': ok, 'pk': pk, 'equipment': '№3, 2а', 'task': 'Метод. указания',
                    'control': 'Защита пр.раб.',
                })
        th = sum(l['hours'] for l in les if not l['practice_prep'])
        pr = sum(l['hours'] for l in les if l['practice_prep'])
        topics.append({
            'name': 'Тема %s %s' % (tnum, x['name']),
            'total_hours': th + pr,
            'practice_hours': pr,
            'lessons': les,
        })
    return topics


def check(name, data):
    """Контрольные суммы перед записью."""
    th = data['theory_hours']
    pr = data['practice_hours']
    at = data['attestation']['hours']
    tot = data['total_hours']
    les_sum = sum(l['hours'] for t in data['topics'] for l in t['lessons'])
    les_pr = sum(l['practice_prep'] for t in data['topics'] for l in t['lessons'])
    topic_sum = sum(t['total_hours'] for t in data['topics'])
    print(f"--- {name}")
    print(f"    теория+практ+атт = {th}+{pr}+{at} = {th+pr+at} (total={tot}) {'✅' if th+pr+at == tot else '❌'}")
    print(f"    Σ уроков = {les_sum} (+атт = {les_sum+at}) {'✅' if les_sum+at == tot else '❌'};  Σ практ = {les_pr} {'✅' if les_pr == pr else '❌'}")
    print(f"    Σ тем = {topic_sum} {'✅' if topic_sum == tot - at else '❌ (должно быть ' + str(tot-at) + ')'}")
    for t in data['topics']:
        s = sum(l['hours'] for l in t['lessons'])
        p = sum(l['practice_prep'] for l in t['lessons'])
        okt = '✅' if s == t['total_hours'] and p == t['practice_hours'] else '❌'
        print(f"      {t['name'][:60]}: Σ={s} (практ={p}) {okt}")
    nums = [l['num'] for t in data['topics'] for l in t['lessons']]
    assert nums == list(range(1, len(nums) + 1)), 'нумерация не сквозная!'
    print(f"    занятий: {len(nums)}, нумерация сквозная ✅")


