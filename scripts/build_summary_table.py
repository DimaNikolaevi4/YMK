def write_table(ws, title, headers, rows, total_row=None, status_col=None,
                col_widths=None, note_lines=None):
    last_col = len(headers) + 1
    setup_sheet(ws, title=title, last_col=last_col)
    for ci, h in enumerate(headers, start=2):
        ws.cell(row=4, column=ci, value=h)
    style_header_row(ws, row_num=4, col_start=2, col_end=last_col)
    r = 5
    for i, row in enumerate(rows):
        for ci, v in enumerate(row, start=2):
            ws.cell(row=r, column=ci, value=v)
        style_data_row(ws, row_num=r, col_start=2, col_end=last_col, row_index=i)
        # числовые — вправо
        for ci, v in enumerate(row, start=2):
            if isinstance(v, (int, float)):
                ws.cell(row=r, column=ci).alignment = align_number()
        # статус — цвет + перенос
        if status_col is not None:
            code = row[status_col - 2]
            cell = ws.cell(row=r, column=status_col)
            color = ST_COLOR.get(code, NEUTRAL_900)
            cell.font = Font(name=FONT_NAME, size=11, color=color, bold=HEADER_BOLD)
            cell.alignment = Alignment(horizontal='center', vertical='center', wrap_text=True)
        r += 1
    if total_row is not None:
        for ci, v in enumerate(total_row, start=2):
            ws.cell(row=r, column=ci, value=v)
        style_total_row(ws, row_num=r, col_start=2, col_end=last_col)
        for ci, v in enumerate(total_row, start=2):
            if isinstance(v, (int, float)):
                ws.cell(row=r, column=ci).alignment = align_number()
        r += 1
    if note_lines:
        r += 2
        for line in note_lines:
            ws.cell(row=r, column=2, value=line).font = font_caption()
            r += 1
    if col_widths:
        from openpyxl.utils import get_column_letter
        for ci, w in col_widths.items():
            ws.column_dimensions[get_column_letter(ci)].width = w
    ws.freeze_panes = 'C5'
    ws.page_setup.orientation = 'landscape'
    ws.page_setup.fitToWidth = 1
    ws.page_setup.fitToHeight = 0
    return r


