# ИТОГИ ПО ВЕДОМОСТИ (проверка: суммы ROWS + практика = ведомость)
# ============================================================================

def totals():
    odd = [r for r in ROWS if r['per'].startswith('Нечёт')]
    even = [r for r in ROWS if r['per'].startswith('Чёт')]
    t_odd = sum(r['theor'] for r in odd)
    t_even = sum(r['theor'] for r in even)
    # ведомость: нечёт 406/479, чёт 630/792, всего 1036/1271 (нагрузка_2026-2027.md)
    v_odd_total = t_odd + 13 + 24 + 36          # + конс.13 + экз.24 + практика УП02 36
    v_even_total = t_even + 9 + 32 + 108 + 13   # + конс.9 + экз.32 + практика УП03 108 + прочие 13
    assert t_odd == 406, t_odd
    assert t_even == 630, t_even
    assert v_odd_total == 479, v_odd_total
    assert v_even_total == 792, v_even_total
    assert t_odd + t_even == 1036
    assert v_odd_total + v_even_total == 1271
    return t_odd, t_even, v_odd_total, v_even_total


